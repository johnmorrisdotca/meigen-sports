#!/usr/bin/env python3
"""Write docs/coverage-people.md: the births and deaths the package holds, by sport and by calendar day, and the gaps. Reads only the published facts."""
from __future__ import annotations

import glob
import json
import statistics
from collections import Counter, defaultdict
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "data/v1/0.1.0/facts"
OUT = ROOT / "docs/coverage-people.md"
CALENDAR = [(date(2024, 1, 1) + timedelta(days=i)).strftime("%m-%d") for i in range(366)]


def load() -> list[dict]:
    rows: list[dict] = []
    for name in sorted(glob.glob(str(FACTS / "store/*.json"))):
        rows.extend(r for r in json.loads(Path(name).read_text(encoding="utf-8"))["records"] if r["category"] in ("player-birthday", "player-death") and r.get("eventDate"))
    return rows


def spread(counts: list[int]) -> str:
    counts = sorted(counts)
    return f"min {counts[0]}, median {int(statistics.median(counts))}, max {counts[-1]}"


def main() -> int:
    people = load()
    manifest = json.loads((FACTS / "manifest.json").read_text(encoding="utf-8"))
    dump = (manifest.get("sources") or {}).get("wikidataDump") or {}
    by_day: dict[str, list[dict]] = defaultdict(list)
    for r in people:
        by_day[r["eventDate"][5:]].append(r)
    sports: dict[str, Counter] = defaultdict(Counter)
    days_of: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in people:
        sports[r["sport"] or "(none)"][r["category"]] += 1
        days_of[r["sport"] or "(none)"][r["eventDate"][5:]] += 1
    n_dump = sum(1 for r in people if r["recordId"].startswith("wikidata:"))
    out = [
        "# Coverage of people: births and deaths, by sport and by day", "",
        "Generated by `python3 -I pipeline/coverage_people.py`. Do not edit the numbers by hand.", "",
        f"The package holds **{len(people):,} births and deaths** with a day-precision date, of **{len(sports)} sports**: {len(people) - n_dump:,} from SPX's own archive and the priority list, "
        f"and **{n_dump:,} from the Wikidata dump** of {dump.get('dumpDate', '?')} (`{dump.get('dumpName', '?')}`, CC0, each with its Q id). "
        "A person is ranked by the number of Wikipedia editions he has; below 30 editions a day, sport and kind keeps its best two with at least 10 editions "
        "(five fewer with an Olympic medal or a Hall of Fame behind him). Wikidata dates are used only at day precision on the Gregorian calendar, from 1850, and never on "
        "January 1, which Wikidata writes for a year-only date about as often as for a real one.", "",
        "## By day", "",
        f"- Births and deaths per day: {spread([len(by_day.get(d, [])) for d in CALENDAR])}.",
        f"- Sports per day: {spread([len({r['sport'] for r in by_day.get(d, [])}) for d in CALENDAR])}.",
        f"- Every one of the 366 days has people; the fewest are {', '.join(f'{d} ({len(by_day[d])})' for d in sorted(CALENDAR, key=lambda d: (len(by_day.get(d, [])), d))[:5])}.",
        "- January 1 holds only the births and deaths that were confirmed before (the English Wikipedia lead states the day): "
        f"{len(by_day.get('01-01', []))} people in {len({r['sport'] for r in by_day.get('01-01', [])})} sports. It is the one day with a gap.", "",
        "## By sport", "",
        "| Sport | People | Births | Deaths | Days with one | Most on a day | Median per day with one |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for sport, c in sorted(sports.items(), key=lambda kv: (-(kv[1]["player-birthday"] + kv[1]["player-death"]), kv[0])):
        per_day = list(days_of[sport].values())
        out.append(f"| `{sport}` | {sum(c.values()):,} | {c['player-birthday']:,} | {c['player-death']:,} | {len(per_day)} | {max(per_day)} | {int(statistics.median(per_day))} |")
    out += ["", "## The gaps", "",
            "- **January 1**, as said above.",
            "- A sport below ten people has no more than the Wikipedia editions allow; a person with fewer than ten editions (five with an Olympic medal or a Hall of Fame) is not published, because a short article is not fame.",
            "- A person whose first occupation is not a sport one, or whose description opens with another trade (a president, an actor), is not published as a sports person; a Julian date is not converted, so it is left out.",
            "- Para and wheelchair sports, and a description that names a crime, are not published (John's rule: no para label, no health).", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(people)} people, {len(sports)} sports")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
