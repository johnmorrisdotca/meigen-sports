#!/usr/bin/env python3
"""Write docs/para-sports.md: the para sport facts the package holds, by sport and kind, the fame rule with its counts, and what is left out. Reads only the published facts."""
from __future__ import annotations

import glob
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "data/v1/0.1.0/facts"
OUT = ROOT / "docs/para-sports.md"
KINDS = ("player-birthday", "player-death", "competition-start", "competition-end", "sport-event")


def main() -> int:
    sports = json.loads((ROOT / "data-sources/para-sports.json").read_text(encoding="utf-8"))
    slugs = {s["slug"] for s in sports["sports"]} | {sports["gamesSlug"]}
    rows: list[dict] = []
    for name in sorted(glob.glob(str(FACTS / "store/*.json"))):
        rows.extend(r for r in json.loads(Path(name).read_text(encoding="utf-8"))["records"] if r.get("sport") in slugs)
    manifest = json.loads((FACTS / "manifest.json").read_text(encoding="utf-8"))
    meta = (manifest.get("sources") or {}).get("wikidataDumpPara") or {}
    report = meta.get("report") or {}
    options = meta.get("options") or {}
    by_sport: dict[str, Counter] = defaultdict(Counter)
    for r in rows:
        by_sport[r["sport"]][r["category"]] += 1
    count = Counter(r["category"] for r in rows)
    fame = report.get("peopleByFameTest") or {}
    left = report.get("leftOut") or {}
    not_famous = next((n for k, n in left.items() if "not famous" in k), 0)
    with_class = next((n for k, n in left.items() if "class code" in k), 0)
    out = [
        "[日本語](para-sports.ja.md) · English", "",
        "# Para sports: wheelchair sports, goalball, boccia and the Paralympic Games", "",
        "Generated by `python3 -I pipeline/coverage_para.py`. Do not edit the numbers by hand.", "",
        f"The package holds **{len(rows):,} facts of para sports** in {len(by_sport)} sports: {count['player-birthday']} births and {count['player-death']} deaths of people, "
        f"{count['competition-start']} starts and {count['competition-end']} ends of editions, and {count['sport-event']} single days. "
        f"They come from the Wikidata dump of {meta.get('dumpDate', '?')} (`{meta.get('dumpName', '?')}`, CC0, each fact with its Q id) through `pipeline/wikidata_dump_para.py`, "
        "which reads the same filtered files as the dump of people and events and writes one extract. Nothing is fetched, so the pass makes no request.", "",
        '<p align="center"><img alt="The favourites for the sport wheelchair tennis: births and deaths of famous people, each with a flag and the phrase wheelchair tennis player and nothing else about the body." src="images/para-desktop.png" width="720"><br><em>A para sport in the demo (<code>?sport=wheelchair-tennis</code>).</em></p>', "",
        "## What is stored: the sport's name and nothing else about the body", "",
        "John's decision of 2026-11-02: the sport itself may be named (`wheelchair-basketball`, `goalball`, `boccia`, `para-swimming`, `paralympics`). Never stored, in any field, sentence, tag or name:", "",
        "- a class code (T54, F42, S9, SB5, BC1, SH6, PR2, WH1 and the like), or the word for a class, a category or a classification;",
        "- an impairment, a diagnosis or any other statement about health or the body;",
        "- the person's own Wikidata description (free text): a person is called by a phrase of a fixed table, a nationality word and the sport (\"Dutch wheelchair tennis player\", \"goalball player\").", "",
        "An event whose name holds a class code or a word for the body is left out. So are Games and bodies set up for a condition and not a sport (the Invictus Games, the Special Olympics, the Deaflympics, IBSA, INAS, CP-ISRA, IWAS), "
        "and a sport whose name states an impairment (blind, deaf, amputee). `test/para-sports.test.ts` and the golden rule `para-facts-name-the-sport-only` fail on a class code or a health word in any para fact, and `pipeline/test_wikidata_dump_para.py` holds the extractor to the same.", "",
        "## Who is published", "",
        "The dump rule (30 Wikipedia editions) would publish nobody here: the best-linked player has 28. A person is published when any one of these is true "
        f"(the counts are of people with a birth or death fact: {report.get('peoplePublished', '?')} people):", "",
        f"- **listed** ({fame.get('listed', 0)}): he is on John's priority list or the 2,000 list;",
        f"- **medallist** ({fame.get('medallist', 0)}): a Paralympic medal (a medal statement, or a first, second or third place at a Paralympic Games), a world or Paralympic champion title or any Hall of Fame, with at least {options.get('medallistEditions', 1)} Wikipedia edition (an article);",
        f"- **deceased** ({fame.get('deceased', 0)}): Wikidata holds a death and he has an English Wikipedia article;",
        f"- **veteran** ({fame.get('veteran', 0)}): he took part in {options.get('veteranGames', 4)} or more Paralympic Games and has {options.get('veteranEditions', 3)} or more editions (an exceptional career);",
        f"- **celebrity** ({fame.get('celebrity', 0)}): {options.get('celebrityEditions', 10)} or more editions (a public figure by the count the package ranks by everywhere).", "",
        "A living person who is none of these is not published. A world record is not in the filtered files, so nobody is chosen by a record alone (left to revisit). "
        "A date is used only at day precision on the Gregorian calendar, from 1850, and never on January 1.", "",
        "## Events", "",
        f"An event is published when it has a day-precision date, a name and at least {options.get('eventEditions', 1)} Wikipedia edition: a Paralympic Games edition, a sport at a Games, a world or regional championship, a tournament. "
        "A start, an end and a single day are three kinds of fact, as for the other events. The place and the winner are said only where Wikidata states them; a national team is named by its country "
        "(\"won by Canada\"), and no person is named as the winner of an event whose name carries a sex marker.", "",
        "## By sport", "",
        "| Sport | Facts | Births | Deaths | Starts | Ends | Single days |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for sport, c in sorted(by_sport.items(), key=lambda kv: (-sum(kv[1].values()), kv[0])):
        out.append(f"| `{sport}` | {sum(c.values())} | {c['player-birthday']} | {c['player-death']} | {c['competition-start']} | {c['competition-end']} | {c['sport-event']} |")
    out.append(f"| **All** | **{len(rows)}** | **{count['player-birthday']}** | **{count['player-death']}** | **{count['competition-start']}** | **{count['competition-end']}** | **{count['sport-event']}** |")
    out += ["", "## Read and left out, with the counts of the last build", ""]
    for reason, n in sorted(left.items(), key=lambda kv: -kv[1]):
        out.append(f"- {n:,} {reason}" if reason.startswith("left out") else f"- Read: {n:,} {reason.removesuffix(' read')}")
    out += ["", "## Left to revisit", "",
            f"- People of the sports above who are not famous by the rule are not published ({not_famous:,} in the dump): a Wikipedia list of Paralympic medallists (CC BY-SA 4.0, read like the Olympic one) would add medallists whose Wikidata item has no medal statement.",
            "- Records (a world or Paralympic record) are not in the filtered dump files; a record needs a new read of the record statements.",
            f"- Events with a class code or a word for the body in the name are left out ({with_class:,}); a version of them without the class would need the discipline's own page, not the class page.",
            "- Sports whose name states an impairment (blind football, amputee football), paragliding and the Deaflympics are not on the list.",
            "- The IPC site and the federations' sites are not used: all rights reserved, no open licence found, and the IPC's `robots.txt` disallows its profiles.", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(rows)} facts, {len(by_sport)} sports")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
