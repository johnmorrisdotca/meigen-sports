#!/usr/bin/env python3
"""Write docs/tags.md: the vocabulary of tags a fact carries, how many facts carry each, the countries and sports by count, and how to ask for them. Reads only the published facts."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "data/v1/0.1.0/facts"
OUT = ROOT / "docs/tags.md"

# (namespace, what it says, where it comes from, index folder or "", an example)
NAMESPACES = [
    ("sport", "the sport", "`sport`", "sports", "`sport:handball`"),
    ("league", "the league", "`league`", "leagues", "`league:nhl`"),
    ("competition", "the competition, where it is not the league", "`competition`", "", "`competition:wc1954`"),
    ("series", "an Olympic Games, a World Cup or a World Championships", "the name of the event or the competition", "series", "`series:olympics`"),
    ("country", "the countries of the people or the teams the fact is about", "`countries` (a person: every country he represents in sport or holds; a game: its teams' `countryCode`)", "countries", "`country:RO`"),
    ("host", "the countries an event was held in", "`hostCountries`", "hosts", "`host:FR`"),
    ("birthcountry", "the country a person's birthplace lies in", "`birthCountry`", "birthcountries", "`birthcountry:RO`"),
    ("team", "a club, by its archive id", "`home`, `away`, `person.franchiseIds`", "teams", "`team:f1413`"),
    ("person", "a person, by Q id", "`person.qid`", "", "`person:Q209518`"),
    ("position", "a playing position", "`position`", "positions", "`position:C`"),
    ("venue", "a venue, by its archive id", "`venueId`", "", "`venue:2078`"),
    ("decade", "the decade of the date", "`eventDate`", "decades", "`decade:1960s`"),
    ("century", "the century of the date", "`eventDate`", "", "`century:20`"),
    ("phase", "regular season, playoffs or exhibition", "`phase`", "", "`phase:playoffs`"),
    ("stage", "the round: final, semi, group", "`stage`", "", "`stage:final`"),
    ("award", "an individual award the person won himself", "`awards`", "awards", "`award:hart-memorial-trophy`"),
    ("title", "a club title the person won", "`championshipName`", "titles", "`title:stanley-cup`"),
    ("honour", "an honour: award winner, champion, Hall of Famer", "`awards`, `championships`, `hallOfFameYear`", "honours", "`honour:award-winner`"),
    ("source", "where the fact comes from", "`source.sourceId`", "", "`source:wikidata`"),
]


def main() -> None:
    manifest = json.loads((FACTS / "manifest.json").read_text(encoding="utf-8"))
    vocabulary = json.loads((FACTS / "index/vocabulary.json").read_text(encoding="utf-8"))
    tags = manifest["tags"]
    total = manifest["records"]
    lines = [
        "# Tags: what a fact is about, and how to ask for it",
        "",
        "Generated by `python3 -I pipeline/coverage_tags.py` (`pnpm data:coverage-tags`). Do not edit the numbers by hand.",
        "",
        f"Every one of the {total:,} facts carries its tags in `tags`: the history types that say what kind of fact it is (`player-birthday`, `championship-win`; [the 46](./categories.md)) and "
        "the namespaced tags below, `namespace:value`, that say what it is about. The namespaced tags are not a second copy of the data: each is built from a field the fact already holds, "
        "by `derivedTags` (`src/tags.ts`), and nothing is guessed, so a fact with no country has no `country:` tag. `tagsOf` lists every tag of a fact; `factsFor` finds by them; "
        "the static files hold an index of ids for the ones a reader asks for most.",
        "",
        "## The vocabulary",
        "",
        "| Namespace | It says | Built from | Values | Facts | Index | Example |",
        "| --- | --- | --- | ---: | ---: | --- | --- |",
    ]
    for namespace, says, source, folder, example in NAMESPACES:
        row = tags.get(namespace, {"values": 0, "facts": 0})
        index = f"`indexes/{folder}/<value>.json`" if folder else "in `tags` only"
        lines.append(f"| `{namespace}` | {says} | {source} | {row['values']:,} | {row['facts']:,} | {index} | {example} |")
    lines += [
        "",
        "A tag's value is letters, digits, hyphens, dots and underscores. A country is an ISO 3166-1 alpha-2 code (`RO`), or the ISO 3166-3 code of a former country that has a flag in Hata "
        "(`SUHH` the Soviet Union, `DDDE` East Germany, `CSHH` Czechoslovakia, `YUCS` Yugoslavia); England, Scotland, Wales and Northern Ireland are `GB`. A person of two countries has both, "
        "and the flag (`flag`, a code a flag set draws) only when he represents one in sport or has one country. A state no code names (the British Raj, the Empire of Japan) is not guessed.",
        "",
        "## Countries",
        "",
        f"{len(vocabulary['countries']):,} country codes. The fifteen with the most facts (all of them, with their counts, are in `index/vocabulary.json`):",
        "",
        "| Country | Facts |",
        "| --- | ---: |",
    ]
    for code, count in list(vocabulary["countries"].items())[:15]:
        lines.append(f"| `{code}` | {count:,} |")
    lines += ["", "## Sports", "", f"{len(vocabulary['sports']):,} sports. The fifteen with the most facts:", "", "| Sport | Facts |", "| --- | ---: |"]
    for slug, count in list(vocabulary["sports"].items())[:15]:
        lines.append(f"| `{slug}` | {count:,} |")
    lines += [
        "",
        "## Asking for them",
        "",
        "In the code, with the facts you already hold (the offline set here):",
        "",
        "```js",
        'import { derivedTags, factsFor, flagOf, tagsOf } from "@johnmorrisdotca/meigen-sports";',
        'import { offline } from "@johnmorrisdotca/meigen-sports/offline";',
        "",
        "const fact = factsFor(offline, { tags: [\"sport:baseball\"] })[0];",
        "console.log(tagsOf(fact).includes(\"sport:baseball\")); // true",
        "console.log(derivedTags(fact).every((tag) => tag.includes(\":\"))); // true",
        "console.log(flagOf(fact) === null || typeof flagOf(fact) === \"string\"); // true",
        "console.log(factsFor(offline, { country: \"US\", tags: [\"sport:baseball\"] }).length > 0); // true",
        "```",
        "",
        "From the static files, one request for each choice (the indexes are ids only) and then the store files the ids are in (a fact is in one of 100 files by its id):",
        "",
        "```js no-run",
        'import { queryFacts } from "@johnmorrisdotca/meigen-sports/load";',
        "",
        "const load = { baseUrl: \"https://johnmorrisdotca.github.io/meigen-sports/\", dataVersion: \"0.1.0\", fetch };",
        "// The Romanian facts of one calendar day, in every sport:",
        "const romanian = await queryFacts({ country: \"RO\", day: \"03-04\" }, load);",
        "// Handball, Romania, the 2000s:",
        "const handball = await queryFacts({ country: \"RO\", sport: \"handball\", decade: \"2000s\" }, load);",
        "```",
        "",
        "`loadCountry(\"RO\", load)` is a country's best forty facts, ranked, in one file. `findPeopleByName(\"gretz\", load)` finds a person by first or last name in one small file, "
        "and `loadFactsById` loads the facts of the ids it returns.",
        "",
        "## What is never a tag",
        "",
        "Sex or gender, ethnicity, religion, politics, family and health are not tags, and no field of a fact holds them: the Wikidata dump was filtered before the package saw it, "
        "para, wheelchair, deaf and blind sport is left out, and `test/tags.test.ts` fails if a tag's namespace or value says any of those words. "
        "A tag for a person's sex would be needed to say a sport is \"women's\"; the package does not, and a sport is its sport.",
        "",
        "## What a tag is not",
        "",
        "- A tag is not an identity: two people may share a name, and the Q id (`person:Q…`) tells them apart.",
        "- Teams and people have no country of their own unless the data says one: a club's country is its league's country as the archive holds it (`countryCode`), a person's is Wikidata's.",
        "- `country:` is about the people and the teams of a fact; where an event was held is `host:`, and where a person was born is `birthcountry:`.",
        "- There is no `city:` or `era:` tag: the archive names a venue's city but holds no id for it, and no era is defined in the data. They would be guesses.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
