#!/usr/bin/env python3
"""Write docs/coverage-events.md: the events and competition editions the package holds, by sport and by calendar day, and the gaps. Reads only the published facts."""
from __future__ import annotations

import glob
import json
import statistics
from collections import Counter, defaultdict
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACTS = ROOT / "data/v1/0.1.0/facts"
OUT = ROOT / "docs/coverage-events.md"
CALENDAR = [(date(2024, 1, 1) + timedelta(days=i)).strftime("%m-%d") for i in range(366)]
CATEGORIES = ("competition-start", "competition-end", "sport-event")


def load() -> list[dict]:
    rows: list[dict] = []
    for name in sorted(glob.glob(str(FACTS / "store/*.json"))):
        rows.extend(r for r in json.loads(Path(name).read_text(encoding="utf-8"))["records"] if r["category"] in CATEGORIES and r.get("eventDate"))
    return rows


def spread(counts: list[int]) -> str:
    counts = sorted(counts)
    return f"min {counts[0]}, median {int(statistics.median(counts))}, max {counts[-1]}"


def main() -> int:
    events = load()
    manifest = json.loads((FACTS / "manifest.json").read_text(encoding="utf-8"))
    dump = (manifest.get("sources") or {}).get("wikidataDumpEvents") or {}
    by_day: dict[str, list[dict]] = defaultdict(list)
    for r in events:
        by_day[r["eventDate"][5:]].append(r)
    sports: dict[str, Counter] = defaultdict(Counter)
    days_of: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    for r in events:
        sports[r["sport"] or "(none)"][r["category"]] += 1
        days_of[r["sport"] or "(none)"][r["eventDate"][5:]] += 1
    edges = [d for d in CALENDAR if d in ("01-01", "12-31")]
    out = [
        "# Coverage of events: competitions and single days, by sport and by day", "",
        "Generated by `python3 -I pipeline/coverage_events.py`. Do not edit the numbers by hand.", "",
        f"The package holds **{len(events):,} events and competition editions** with a day-precision date, of **{len(sports)} sports**, from the Wikidata dump of {dump.get('dumpDate', '?')} "
        f"(`{dump.get('dumpName', '?')}`, CC0, each with its Q id): {sum(1 for r in events if r['category'] == 'competition-start'):,} that began, "
        f"{sum(1 for r in events if r['category'] == 'competition-end'):,} that ended and {sum(1 for r in events if r['category'] == 'sport-event'):,} that took place on one day; "
        f"{sum(1 for r in events if r.get('winnerName')):,} name a winner and {sum(1 for r in events if r.get('eventPlace')):,} a place, as Wikidata states them. "
        "An event is ranked by the number of Wikipedia editions of its page: everything with 20 or more, and below that the best two of each day, sport and kind with 5 or more. "
        "A date that is January 1 or December 31 is left out (a season is written that way), and so is an edition named for a season or a play-off, a league SPX's own archive holds, "
        "para, wheelchair, deaf and blind sport, and an edition whose end is before its start.", "",
        "## By day", "",
        f"- Events per day: {spread([len(by_day.get(d, [])) for d in CALENDAR if d not in edges])} (the two edges of the year excepted).",
        f"- Sports per day: {spread([len({r['sport'] for r in by_day.get(d, [])}) for d in CALENDAR if d not in edges])}.",
        f"- The quietest days are {', '.join(f'{d} ({len(by_day[d])})' for d in sorted((d for d in CALENDAR if d not in edges), key=lambda d: (len(by_day.get(d, [])), d))[:5])}.",
        f"- {', '.join(edges)} hold none: Wikidata writes a year's first and last day for a season or a year-only date, and the dump cannot tell them apart.", "",
        "## By sport", "",
        "| Sport | Events | Began | Ended | One day | Days with one | Most on a day |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for sport, c in sorted(sports.items(), key=lambda kv: (-sum(kv[1].values()), kv[0])):
        per_day = list(days_of[sport].values())
        out.append(f"| `{sport}` | {sum(c.values()):,} | {c['competition-start']:,} | {c['competition-end']:,} | {c['sport-event']:,} | {len(per_day)} | {max(per_day)} |")
    out += ["", "## The gaps", "",
            "- **January 1 and December 31**, as said above.",
            "- A competition whose page has fewer than five editions is not published, and one with fewer than 20 only when it is among the best two of its day and sport.",
            "- A place or a winner is named only where the item states it; a winner that is a person is not named in an event whose name carries a sex marker (the event keeps its name, and no person is told to be of a sex), and a team is named by its country.",
            "- A match, a stage or a bout is a fact only when the item holds a day and a name; the scores and the players of a game are not in these facts.", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT}: {len(events)} events, {len(sports)} sports")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
